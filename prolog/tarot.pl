% --- Helper: All cards of a suit ---
cards_of(Suit, Cards) :-
    findall(Card, tarot_card(Card, minor_arcana, Suit), Cards).

% --- Helper: All major arcana ---
major_arcana_cards(Cards) :-
    findall(Card, tarot_card(Card, major_arcana, _), Cards).

% --- Helper: All minor arcana ---
minor_arcana_cards(Cards) :-
    findall(Card, tarot_card(Card, minor_arcana, _), Cards).

% --- Helper: All tarot cards ---
all_tarot_cards(Cards) :-
    findall(Card, tarot_card(Card, _, _), Cards).
